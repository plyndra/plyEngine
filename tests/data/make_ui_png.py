#!/usr/bin/env python3
"""Generates tests/data/ui.png: the pixel fixture for the ui_atlas.json atlas.

Why this exists (M1a a3): E-a3.1 grades "alpha-derived margins equal declared
margins on the fixture", which needs real pixels. tools/artgen is still an
empty skeleton, so the fixture is built here instead of being generated by the
art pipeline — tests/data is test data, and the art-lint provenance rule
(E-c1.x) is scoped to shipped/generated assets, not fixtures. Decision recorded
2026-11-10 (plyengine::a9-a3-predecisions).

Geometry is read from ui_atlas.json, so the PNG cannot drift from the atlas:
every region rect comes from the document. What this script adds is the *alpha
contour* each region needs in order for derivation to reproduce the atlas's
recorded margins exactly:

  * a region with margins [l, t, r, b] gets a fully transparent ring of that
    thickness inside its own rect (interior opaque);
  * a region that declares no margins is painted opaque edge to edge.

That is the shape §3 of UI_FRAMEWORK.md describes — "the run-length of uniform
border pixels per side" — for art whose sliceable padding is transparent.

Output is deterministic: the same atlas document always produces the same
bytes (fixed palette derivation, fixed zlib level, no timestamps).

Usage: python3 tests/data/make_ui_png.py [--check]
       --check  regenerate in memory and compare against the committed file
"""

import hashlib
import json
import os
import struct
import sys
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
ATLAS = os.path.join(HERE, "ui_atlas.json")
OUT = os.path.join(HERE, "ui.png")

# The canvas must contain every region; it is not a power of two, because the
# regions are laid out for legibility rather than for GPU tiling. Row 0 is the
# top of the image, like Image's decoded buffer.
WIDTH, HEIGHT = 160, 128


def palette(name):
    """A stable opaque colour per region name (FNV-1a over the name bytes)."""
    h = 0xCBF29CE484222325
    for b in name.encode():
        h = ((h ^ b) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    # Keep channels in a pleasant mid range so no colour is mistaken for the
    # transparent ring (alpha is what derivation reads; colour is for humans).
    return (40 + (h & 0xBF), 40 + ((h >> 8) & 0xBF), 40 + ((h >> 16) & 0xBF))


def margins_of(entry):
    m = entry.get("margins")
    if not m:
        return (0, 0, 0, 0)
    return tuple(m)


def build():
    with open(ATLAS) as f:
        atlas = json.load(f)

    # Transparent canvas: everything the atlas does not cover is alpha 0.
    pixels = [[(0, 0, 0, 0)] * WIDTH for _ in range(HEIGHT)]

    for name, entry in atlas["regions"].items():
        x, y, w, h = entry["x"], entry["y"], entry["w"], entry["h"]
        left, top, right, bottom = margins_of(entry)
        r, g, b = palette(name)
        for row in range(y, y + h):
            for col in range(x, x + w):
                inside_band = (
                    col < x + left
                    or col >= x + w - right
                    or row < y + top
                    or row >= y + h - bottom
                )
                if inside_band:
                    # Transparent padding. The colour is deliberately noisy so
                    # the derivation's rule is provably about the ALPHA channel:
                    # a reader that measured a colour channel instead would see
                    # a non-uniform ring and derive 0. Alpha is uniformly 0,
                    # which is what UI_FRAMEWORK.md §3's contour means.
                    pixels[row][col] = ((row * 17 + col * 5) & 0xFF, (col * 11) & 0xFF,
                                       (row * 3 + 7) & 0xFF, 0)
                else:
                    pixels[row][col] = (r, g, b, 255)

    return pixels


def encode(pixels):
    raw = bytearray()
    for row in pixels:
        raw.append(0)  # filter type 0 (None), so the bytes are trivially stable
        for r, g, b, a in row:
            raw += bytes((r, g, b, a))

    def chunk(tag, payload):
        return (
            struct.pack(">I", len(payload))
            + tag
            + payload
            + struct.pack(">I", zlib.crc32(tag + payload) & 0xFFFFFFFF)
        )

    ihdr = struct.pack(">IIBBBBB", WIDTH, HEIGHT, 8, 6, 0, 0, 0)  # 8-bit RGBA
    return (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", ihdr)
        + chunk(b"IDAT", zlib.compress(bytes(raw), 9))
        + chunk(b"IEND", b"")
    )


def main():
    data = encode(build())
    digest = hashlib.sha256(data).hexdigest()

    if "--check" in sys.argv:
        with open(OUT, "rb") as f:
            committed = f.read()
        if committed != data:
            print(f"DRIFT: {OUT} differs from what this script produces")
            print(f"  committed sha256 {hashlib.sha256(committed).hexdigest()}")
            print(f"  generated sha256 {digest}")
            return 1
        print(f"ok: {OUT} matches (sha256 {digest})")
        return 0

    with open(OUT, "wb") as f:
        f.write(data)
    print(f"wrote {OUT} ({len(data)} bytes, sha256 {digest})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
