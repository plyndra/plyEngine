#!/usr/bin/env python3
"""Emit tests/data/tileset_blob47.json — the b1.3 terrain-skeleton fixture.

One tile per canonical blob-47 mask (kBlobMasks in TileSet.hpp), ids 0..46 in
kBlobMasks order, so the b1.3 table-identity pin is: fixture tile i's mask ==
kBlobMasks[i] for all 47. No art is needed yet (regions only); the real
terrain pixels arrive with M1c's c1.1.

The mask list below must equal kBlobMasks. It is deliberately NOT read from
the C++ header: the identity pin in tests/tileset.cpp compares THIS fixture
against the header's table element by element, so a header edit or a list
edit here breaks the pin instead of silently staying in sync — the same
discipline as make_ui_png.py deriving its geometry from ui_atlas.json.

Usage: make_blob47_tileset.py [--check]
  default: write the fixture next to this script
  --check: verify the committed file matches the generated bytes, exit 1 on
           drift (CI-able)
"""

import sys
from pathlib import Path

# == kBlobMasks (TileSet.hpp) — the 47 canonical blob masks, ascending.
MASKS = [
    0, 1, 4, 5, 7, 16, 17, 20, 21, 23, 28, 29, 31,
    64, 65, 68, 69, 71, 80, 81, 84, 85, 87, 92, 93, 95,
    112, 113, 116, 117, 119, 124, 125, 127,
    193, 197, 199, 209, 213, 215, 221, 223,
    241, 245, 247, 253, 255,
]


def emit() -> str:
    assert len(MASKS) == 47, "the blob-47 table holds exactly 47 masks"
    assert MASKS == sorted(MASKS), "canonical order is ascending"
    lines = [
        "{",
        '  "name": "blob47",',
        '  "image": "tileset_blob47.png",',
        '  "tile_width": 16,',
        '  "tile_height": 16,',
        '  "tiles": [',
    ]
    for i, mask in enumerate(MASKS):
        # One 16 px cell per mask, left to right in canonical order.
        lines.append(
            '    {"id": %d, "region": {"x": %d, "y": 0, "w": 16, "h": 16}, '
            '"solid": false, "mask": %d, "variant": "grass", '
            '"palette": "overworld"}%s' % (i, i * 16, mask, "," if i < 46 else "")
        )
    lines.append("  ]")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> int:
    target = Path(__file__).resolve().parent / "tileset_blob47.json"
    text = emit()
    if "--check" in sys.argv[1:]:
        if not target.exists():
            print(f"blob47 fixture missing: {target}", file=sys.stderr)
            return 1
        if target.read_text() != text:
            print("blob47 fixture drifted from the generator", file=sys.stderr)
            return 1
        print("blob47 fixture matches the generator")
        return 0
    target.write_text(text)
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
